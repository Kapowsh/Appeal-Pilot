"""Summarize California DMHC Independent Medical Review decisions for the services Appeal-Pilot covers.

Usage: uv run python scripts/imr_patterns.py path/to/imr.csv > data/imr_patterns.md
The CSV is the public "Independent Medical Review (IMR) Determinations, Trend" dataset (de-identified).
Matching is keyword-based on each decision's case summary, so counts are approximate.
"""
import csv
import html
import re
import sys

SOURCE = "https://data.ca.gov/dataset/independent-medical-review-imr-determinations-trend"

_BIOLOGICS = r"Humira|adalimumab|Enbrel|etanercept|Stelara|ustekinumab|Cosentyx|secukinumab|Skyrizi|Tremfya|Taltz"
SERVICES = {
    "MRI lumbar spine": r"\bMRI\b[^.]{0,60}(lumbar|low(er)? back|L-?spine)|(lumbar|lumbosacral)[^.]{0,30}\bMRI\b",
    "Knee arthroscopy": r"knee arthroscop|arthroscop[^.]{0,40}knee|meniscectom",
    "Total hip arthroplasty": r"total hip (arthroplasty|replacement)|hip replacement",
    "Physical therapy visit extension": r"(additional|further|continued|more)[^.]{0,30}physical therapy",
    "Sleep apnea testing": r"polysomnogra|sleep study|sleep apnea test",
    "Continuous glucose monitor": r"continuous glucose monitor|\bCGMS?\b|Dexcom|Freestyle Libre",
    "GLP-1 receptor agonist": r"semaglutide|Ozempic|liraglutide|Victoza|dulaglutide|Trulicity|tirzepatide|Mounjaro|GLP-1",
    "Bariatric surgery": r"bariatric|gastric bypass|sleeve gastrectomy|gastric sleeve|lap(aroscopic)? band",
    "Biologic for plaque psoriasis": rf"psoria[^.]{{0,80}}({_BIOLOGICS}|biologic)|({_BIOLOGICS})[^.]{{0,80}}psoria",
    "Biologic for rheumatoid arthritis":
        rf"rheumatoid arthritis[^.]{{0,80}}({_BIOLOGICS}|Orencia|Actemra|biologic)|({_BIOLOGICS})[^.]{{0,80}}rheumatoid",
    "CT abdomen and pelvis": r"\bCT\b[^.]{0,40}(abdomen|pelvis)|(abdomen|abdominal|pelvi)[^.]{0,30}\bCT\b",
}
THEMES = {
    "Conservative therapy": r"conservative (therapy|treatment|management|care)",
    "Step therapy / alternatives": r"formulary|step therapy|metformin|methotrexate|(trial|failure) of (other|alternative)",
    "Red flags / neuro deficit": r"red flag|neurolog(ic|ical) deficit",
    "BMI threshold": r"\bBMI\b|body mass index",
    "Insufficient documentation": r"insufficient|lack of documentation|not (been )?(provided|submitted|documented)",
    "Experimental / investigational": r"experimental|investigational",
    "Functional progress": r"functional (improvement|gains|progress)|plateau",
    "A1c / insulin use": r"\b(A1c|HbA1c)\b|insulin",
}
_SERVICE_RX = {k: re.compile(v, re.I) for k, v in SERVICES.items()}
_THEME_RX = {k: re.compile(v, re.I) for k, v in THEMES.items()}


def _parts(findings: str) -> tuple[str, str]:
    text = html.unescape(findings or "")
    head, _, rest = text.partition("Findings:")
    return head, rest


def match_service(row: dict) -> str | None:
    head, _ = _parts(row.get("Findings", ""))
    return next((name for name, rx in _SERVICE_RX.items() if rx.search(head)), None)


def summarize(rows) -> dict:
    out = {}
    for r in rows:
        if not (r.get("Report Year") or "").isdigit():
            continue  # malformed rows where free text spilled into the year column
        name = match_service(r)
        if name is None:
            continue
        s = out.setdefault(name, {"n": 0, "overturned": 0, "years": None, "themes": {t: 0 for t in THEMES}})
        year = int(r["Report Year"])
        s["n"] += 1
        s["overturned"] += r.get("Determination", "").startswith("Overturned")
        s["years"] = (min(year, s["years"][0]), max(year, s["years"][1])) if s["years"] else (year, year)
        text = " ".join(_parts(r.get("Findings", "")))
        for t, rx in _THEME_RX.items():
            s["themes"][t] += bool(rx.search(text))
    return out


def render(summary: dict, source: str = SOURCE) -> str:
    lines = ["# Real-world denial patterns (California IMR)", "",
             f"Source: California DMHC Independent Medical Review determinations, de-identified public data: {source}",
             "Generated by `scripts/imr_patterns.py`. Services are matched by keyword on each case summary, so counts "
             "are approximate. Themes are the share of decisions whose summary or findings mention the topic.", "",
             "| Service | IMR decisions | Overturned | Years | Most common themes |", "|---|---|---|---|---|"]
    for name in SERVICES:
        s = summary.get(name)
        if not s:
            continue
        top = sorted(((v, t) for t, v in s["themes"].items() if v), reverse=True)[:3]
        themes = ", ".join(f"{t} ({round(100 * v / s['n'])}%)" for v, t in top) or "-"
        lines.append(f"| {name} | {s['n']} | {round(100 * s['overturned'] / s['n'])}% | "
                     f"{s['years'][0]}-{s['years'][1]} | {themes} |")
    return "\n".join(lines) + "\n"


if __name__ == "__main__":
    with open(sys.argv[1], encoding="utf-8", errors="replace", newline="") as f:
        sys.stdout.write(render(summarize(csv.DictReader(f))))
